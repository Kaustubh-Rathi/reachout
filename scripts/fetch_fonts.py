"""Fetch Inter and JetBrains Mono, including real weight rendering.

Background: the shipped ui/fonts/fonts.css declared Inter at weights 400, 500,
600, 700 and 800 but pointed every one of them at Inter-400.woff2. Every bold
and semibold in the dashboard therefore rendered at regular weight, so visual
hierarchy came only from colour and size. That is a large part of why the UI
read as flat and generic.

Google Fonts serves these families as *variable* fonts: a single woff2 covers
the whole weight axis. The correct declaration is one @font-face per family with
``font-weight: 100 900`` (a range), not one file per weight. Verified by hash:
requesting 400/500/600/700 returns four byte-identical files.

Usage::

    uv run python scripts/fetch_fonts.py
"""

from __future__ import annotations

import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "ui" / "fonts"

UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
)

# family query -> (css family name, output file, declared weight range)
FAMILIES = [
    ("Inter:wght@100..900", "Inter", "Inter-var.woff2", "100 900"),
    ("JetBrains+Mono:wght@100..800", "JetBrains Mono", "JetBrainsMono-var.woff2", "100 800"),
]

LATIN_RANGE = (
    "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, "
    "U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, "
    "U+2212, U+2215, U+FEFF, U+FFFD"
)


def _get(url: str) -> bytes:
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=60) as response:
        return response.read()


def _latin_blocks(css: str) -> list[str]:
    blocks = re.findall(r"/\* latin \*/\s*@font-face \{(.*?)\}", css, re.S)
    if not blocks:
        raise SystemExit("ERROR: no latin @font-face blocks found in Google CSS")
    return blocks


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    faces: list[tuple[str, str, str]] = []

    for query, css_name, filename, weight_range in FAMILIES:
        css = _get(
            f"https://fonts.googleapis.com/css2?family={query}&display=swap"
        ).decode("utf-8")
        block = _latin_blocks(css)[0]

        declared = re.search(r"font-weight:\s*([^;]+);", block)
        if not declared:
            raise SystemExit(f"ERROR: no font-weight in {css_name} latin block")
        if " " not in declared.group(1).strip():
            raise SystemExit(
                f"ERROR: {css_name} is not served as a variable font "
                f"(font-weight: {declared.group(1).strip()}); this script assumes "
                "a weight range"
            )

        src = re.search(r"url\((https://[^)]+\.woff2)\)", block)
        if not src:
            raise SystemExit(f"ERROR: no woff2 source for {css_name}")

        data = _get(src.group(1))
        if len(data) < 5000:
            raise SystemExit(f"ERROR: suspiciously small download for {filename}")

        target = FONT_DIR / filename
        target.write_bytes(data)
        print(f"saved {filename} ({len(data):,} bytes, weights {weight_range})")
        faces.append((css_name, filename, weight_range))

    lines = [
        "/* Self-hosted variable font faces.",
        "   One file per family covers the whole weight axis; declaring separate",
        "   files per weight is what previously made every bold render as regular.",
        "   Generated by scripts/fetch_fonts.py - do not hand-edit. */",
    ]
    for css_name, filename, weight_range in faces:
        lines.extend(
            [
                "/* latin */",
                "@font-face {",
                f"  font-family: '{css_name}';",
                "  font-style: normal;",
                f"  font-weight: {weight_range};",
                "  font-display: swap;",
                f"  src: url(/ui/fonts/{filename}) format('woff2');",
                f"  unicode-range: {LATIN_RANGE};",
                "}",
            ]
        )

    css_out = FONT_DIR / "fonts.css"
    css_out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {css_out.relative_to(ROOT)} ({len(faces)} variable faces)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
